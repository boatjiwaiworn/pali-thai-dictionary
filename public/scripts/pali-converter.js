export function sinhalaToThai(text) {
    if (!text) return '';
    const map = {
        'ක': 'ก', 'ඛ': 'ข', 'ග': 'ค', 'ඝ': 'ฆ', 'ඞ': 'ง',
        'ච': 'จ', 'ඡ': 'ฉ', 'ජ': 'ช', 'ඣ': 'ฌ', 'ඤ': 'ญ',
        'ට': 'ฏ', 'ඨ': 'ฐ', 'ඩ': 'ฑ', 'ඪ': 'ฒ', 'ණ': 'ณ',
        'ත': 'ต', 'ථ': 'ถ', 'ද': 'ท', 'ධ': 'ธ', 'න': 'น',
        'ප': 'ป', 'ඵ': 'ผ', 'බ': 'พ', 'භ': 'ภ', 'ම': 'ม',
        'ය': 'ย', 'ර': 'ร', 'ල': 'ล', 'ළ': 'ฬ', 'ව': 'ว',
        'ස': 'ส', 'හ': 'ห',
        'අ': 'อ', 'ආ': 'อา', 'ඉ': 'อิ', 'ඊ': 'อี', 'උ': 'อุ', 'ඌ': 'อู', 'එ': 'อเ', 'ඔ': 'อโ',
        'ා': 'า', 'ි': '\u0E34', 'ී': '\u0E35', 'ු': '\u0E38', 'ූ': '\u0E39', 'ෙ': 'เ', 'ො': 'โ',
        'ං': '\u0E4D', 'ඃ': 'ะ', '්': '\u0E3A'
    };

    let result = '';
    for (let char of text) {
        result += map[char] || char;
    }
    
    // Swap เ and โ to appear BEFORE consonant
    result = result.replace(/([ก-ฮ])([เโ])/g, '$2$1');
    return result;
}
